ALL_HEADERS = frozenset(ENGLISH_HEADERS) | frozenset(
    header for _language, headers in LOCALIZED_HEADERS.values() for header in headers if header
)

# casefolded header -> a spelling Google lists. Only a fallback: two listed
# headers differ by case alone ("Featured Hotels" / en-GB "Featured hotels",
# Bulgarian "Модели" / Serbian "модели"), so an exact match always wins.
_CASEFOLDED: dict[str, str] = {}
for _header in sorted(ALL_HEADERS, key=lambda h: (h not in ENGLISH_HEADERS, h)):
    _CASEFOLDED.setdefault(_header.casefold(), _header)


def canonical_header(header: str) -> str | None:
    """The listed spelling of ``header`` (exact first, then any case), or None."""
    header = (header or "").strip()
    if header in ALL_HEADERS:
        return header
    return _CASEFOLDED.get(header.casefold())


def english_header(header: str) -> str | None:
    """The English header a listed header translates (``"Typen"`` -> ``"Types"``)."""
    canonical = canonical_header(header)
    if canonical is None:
        return None
    if canonical in ENGLISH_HEADERS:
        return canonical
    for _language, headers in LOCALIZED_HEADERS.values():
        if canonical in headers:
            return ENGLISH_HEADERS[headers.index(canonical)]
    return None

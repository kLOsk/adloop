def read_source(source: str) -> str:
    if source.startswith("https://"):
        with urllib.request.urlopen(source, timeout=30) as response:
            return response.read().decode("utf-8")
    path = Path(source).expanduser()
    if not path.is_file():
        raise SystemExit(f"Rules file not found: {path}")
    return path.read_text(encoding="utf-8")


def strip_frontmatter(content: str) -> str:
    if not content.startswith("---"):
        return content
    end = content.index("\n---", 3)
    return content[end + 4 :].lstrip("\n")


def drop_sections(body: str) -> str:
    lines = body.splitlines(keepends=True)
    for prefix in CLOUD_DROPPED_SECTIONS:
        start = next((i for i, line in enumerate(lines) if line.startswith(prefix)), None)
        if start is None:
            raise SystemExit(
                f"The upstream rules no longer have a section starting {prefix!r}. "
                f"Update CLOUD_DROPPED_SECTIONS in {Path(__file__).name}."
            )
        level = len(prefix) - len(prefix.lstrip("#"))
        end = next(
            (
                i
                for i in range(start + 1, len(lines))
                if re.match(rf"#{{1,{level}}} ", lines[i])
            ),
            len(lines),
        )
        del lines[start:end]
    body = "".join(lines)

    leftovers = [
        f"  line {number}: {line.strip()[:120]}"
        for number, line in enumerate(body.splitlines(), start=1)
        if any(re.search(marker, line) for marker in CLOUD_UNAVAILABLE_MARKERS)
    ]
    if leftovers:
        raise SystemExit(
            "The upstream rules mention tools AdLoop Cloud doesn't offer outside "
            "the dropped sections. Extend CLOUD_DROPPED_SECTIONS or rewrite them.\n"
            + "\n".join(leftovers)
        )
    return body


def to_cloud(body: str) -> str:
    body = drop_sections(body)
    missing = [old for old, _ in CLOUD_REPLACEMENTS if old not in body]
    if missing:
        listing = "\n".join(f"  - {old[:100]}" for old in missing)
        raise SystemExit(
            "The upstream rules changed: these Cloud replacements no longer "
            f"match. Update CLOUD_REPLACEMENTS in {Path(__file__).name}.\n{listing}"
        )
    for old, new in CLOUD_REPLACEMENTS:
        body = body.replace(old, new)

    leftovers = []
    for number, line in enumerate(body.splitlines(), start=1):
        for marker in SELF_HOSTED_MARKERS:
            if re.search(marker, line):
                leftovers.append(f"  line {number}: {line.strip()[:120]}")
                break
    if leftovers:
        raise SystemExit(
            "The upstream rules contain self-hosted instructions that have no "
            f"Cloud rewrite yet. Add them to CLOUD_REPLACEMENTS.\n"
            + "\n".join(leftovers)
        )
    return body


def split_sections(body: str) -> list[str]:
    """Split the body into chunks, each starting at a level-2 heading."""
    parts = re.split(r"(?m)^(?=## )", body)
    return [part for part in parts if part]


def build_skill(body: str) -> dict[Path, str]:
    sections = split_sections(body)
    files: dict[Path, str] = {}
    kept: list[str] = []
    found = set()
    for section in sections:
        heading = section.splitlines()[0].strip()
        match = next((ref for ref in REFERENCE_SECTIONS if ref[0] == heading), None)
        if match is None:
            kept.append(section)
            continue
        found.add(heading)
        _, relative, hint = match
        files[SKILL_DIR / relative] = GENERATED_NOTE + "\n" + section.rstrip() + "\n"
        kept.append(f"{heading}\n\nSee [{relative}]({relative}). {hint}\n\n")

    missing = [ref[0] for ref in REFERENCE_SECTIONS if ref[0] not in found]
    if missing:
        raise SystemExit(
            "The upstream rules no longer have these sections: "
            + ", ".join(missing)
            + f". Update REFERENCE_SECTIONS in {Path(__file__).name}."
        )

    skill_body = "".join(kept).rstrip() + "\n"
    files[SKILL_FILE] = SKILL_FRONTMATTER + "\n" + GENERATED_NOTE + "\n" + skill_body
    return files


def render(source: str) -> dict[Path, str]:
    body = to_cloud(strip_frontmatter(read_source(source))).rstrip() + "\n"
    files = build_skill(body)
    files[CURSOR_RULE_FILE] = CURSOR_FRONTMATTER + "\n" + GENERATED_NOTE + "\n" + body
    files[GEMINI_FILE] = GENERATED_NOTE + "\n" + body
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--source",
        help="Path or https URL of adloop.mdc (default: sibling checkout, "
        "else GitHub main)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Don't write; exit 1 if any generated file is out of date",
    )
    args = parser.parse_args()

    source = args.source or (
        str(LOCAL_SOURCE) if LOCAL_SOURCE.is_file() else REMOTE_SOURCE
    )
    files = render(source)

    stale_references = sorted(
        path
        for path in (SKILL_DIR / "references").glob("*.md")
        if path not in files
    )

    if args.check:
        stale = [
            path
            for path, content in files.items()
            if not path.is_file() or path.read_text(encoding="utf-8") != content
        ]
        stale += stale_references
        if stale:
            print("Out of date (run scripts/plugins/sync_skill.py):")
            for path in stale:
                print(f"  {path.relative_to(REPO_ROOT)}")
            return 1
        print(f"Generated rules are up to date with {source}")
        return 0

    for path in stale_references:
        path.unlink()
    for path, content in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(REPO_ROOT)}")
    print(f"source: {source}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
